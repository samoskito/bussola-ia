// UI integration with synthetic session and in-memory domain only. All APIs intercepted.
const assert = require('node:assert/strict');
const { path, load } = require('./helpers.cjs');
const { createDemoAdminUsersStore } = load('domain');
const { chromium } = require(path.join(process.env.ADMIN_BROWSER_MODULES, 'playwright'));
const base = process.env.ADMIN_BROWSER_BASE_URL || 'http://127.0.0.1:3100';
assert.equal(new URL(base).hostname, '127.0.0.1', 'UI tests must use a loopback server');
assert.equal(new URL(base).protocol, 'http:');
const store = createDemoAdminUsersStore();
const mixedAccess = [
  { agentType: 'comunicacao', enabled: true, expiresAt: '2098-06-01' },
  { agentType: 'apresentacao', enabled: true, expiresAt: '2098-07-01' },
  { agentType: 'conversas_dificeis', enabled: true, expiresAt: null },
  { agentType: 'postagem', enabled: true, expiresAt: '2099-08-01' },
];
store.setAccess('demo-user-1', { revision: store.get('demo-user-1').revision, access: mixedAccess, reason: 'Fixture local com validades individuais mistas' }, 'synthetic-admin');
const accessBodies = [], createBodies = [];
const accessState = user => user.access.map(({ agentType, enabled, expiresAt }) => ({ agentType, enabled, expiresAt }));
const fs = require('node:fs'), screenshotDir = process.env.ADMIN_BROWSER_SCREENSHOT_DIR || path.join(require('node:os').tmpdir(), 'bussola-admin-users-ui');
fs.mkdirSync(screenshotDir, { recursive: true });
let browser, role = 'admin', apiStatus = 200;
const errors = [];
(async () => {
  browser = await chromium.launch({ headless: true, ...(process.env.ADMIN_BROWSER_EXECUTABLE ? { executablePath: process.env.ADMIN_BROWSER_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: 'auth_token', value: 'synthetic-ui-only', url: base, httpOnly: true }]);
  await context.route('**/*', async route => {
    const req = route.request(), url = new URL(req.url());
    if (url.origin !== base) return route.abort();
    if (!url.pathname.startsWith('/api/')) return route.continue();
    if (url.pathname === '/api/auth/session') return route.fulfill({ json: { user: role === 'none' ? null : { id: '10000000-0000-4000-8000-000000000001', nome: 'Admin Demo', email: 'admin@example.invalid', nivel: role, created_at: new Date().toISOString(), plano: 'Todas' } } });
    if (url.pathname === '/api/chats') return route.fulfill({ json: { chats: [] } });
    if (!url.pathname.startsWith('/api/admin/users')) return route.fulfill({ status: 403, json: { error: 'External data prohibited' } });
    if (apiStatus !== 200) return route.fulfill({ status: apiStatus, json: { error: 'Synthetic unavailable' } });
    try {
      const body = req.postDataJSON(), parts = url.pathname.split('/').filter(Boolean).slice(3);
      let result;
      if (parts[0] === 'demo-password') result = store.consumeInvite(body.token);
      else if (!parts.length && req.method() === 'GET') result = store.list({ q: url.searchParams.get('q') || '', agentType: url.searchParams.get('agentType') || '', status: url.searchParams.get('status') || '', page: Number(url.searchParams.get('page') || 1), pageSize: Number(url.searchParams.get('pageSize') || 8) });
      else if (!parts.length) { createBodies.push(body); result = { user: store.create(body, 'synthetic-admin') }; }
      else if (parts[1] === 'audit') result = { events: store.audit(parts[0]) };
      else if (parts[1] === 'access') { accessBodies.push(body); result = { user: store.setAccess(parts[0], body, 'synthetic-admin') }; }
      else if (parts[1] === 'invite') result = store.issueInvite(parts[0], body, 'synthetic-admin', base);
      else if (req.method() === 'PATCH') result = { user: store.update(parts[0], body, 'synthetic-admin') };
      else result = { user: store.get(parts[0]) };
      return route.fulfill({ json: result });
    } catch (err) { return route.fulfill({ status: err.status || 500, json: { error: err.message, code: err.code } }); }
  });
  const page = await context.newPage(); page.setDefaultTimeout(20000); page.on('pageerror', err => errors.push(err.message));
  console.log('Opening local demo');
  await page.goto(base + '/dashboard/users', { waitUntil: 'networkidle', timeout: 90000 });
  await page.getByRole('button', { name: /Novo usuário/ }).waitFor();
  console.log('Panel loaded');
  await page.getByRole('button', { name: /Ana Exemplo/ }).click();
  await page.getByRole('button', { name: 'Gerenciar acessos', exact: true }).click();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.getByRole('checkbox').count(), 4);
  assert.equal(await dialog.getByRole('checkbox').first().isChecked(), true);
  const expiries = dialog.locator('input[type="date"]');
  assert.equal(await expiries.count(), 4);
  assert.deepEqual(await expiries.evaluateAll(inputs => inputs.map(input => input.value)), mixedAccess.map(item => item.expiresAt || ''), 'Opening editor preserves every mixed expiry');
  await expiries.first().fill('2098-06-15');
  await dialog.getByLabel('Motivo da alteração').fill('Renovação de somente uma IA simulada');
  await page.screenshot({ path: path.join(screenshotDir, 'admin-users-individual-editor-desktop.png') });
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  await dialog.getByRole('heading', { name: 'Confira antes de salvar' }).waitFor();
  assert.equal(await dialog.getByRole('heading', { name: 'Confira antes de salvar' }).evaluate(el => document.activeElement === el), true, 'Review starts at its heading for keyboard users');
  const reviewCards = dialog.getByRole('region', { name: /^Revisão de/ });
  assert.equal(await reviewCards.count(), 4);
  assert.equal(await dialog.getByText('Será alterada', { exact: true }).count(), 1);
  assert.equal(await dialog.getByText('Mantida', { exact: true }).count(), 3);
  assert.match(await reviewCards.first().innerText(), /01\/06\/2098 \(inclusive\)/);
  assert.match(await reviewCards.first().innerText(), /15\/06\/2098 \(inclusive\)/);
  assert.match(await reviewCards.nth(2).innerText(), /Sem vencimento/);
  assert.match(await reviewCards.last().innerText(), /01\/08\/2099 \(inclusive\)/);
  await page.screenshot({ path: path.join(screenshotDir, 'admin-users-individual-review-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.evaluate(el => { el.scrollTop = 0; });
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), 'Individual review fits the mobile dialog');
  await page.screenshot({ path: path.join(screenshotDir, 'admin-users-individual-review-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await dialog.getByRole('button', { name: 'Voltar e ajustar' }).click();
  assert.deepEqual(await expiries.evaluateAll(inputs => inputs.map(input => input.value)), ['2098-06-15', '2098-07-01', '', '2099-08-01']);
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  await dialog.getByRole('button', { name: 'Confirmar na demo' }).click();
  await page.getByText('Alteração salva somente na demonstração.', { exact: true }).waitFor();
  const afterRenewal = mixedAccess.map((item, index) => index === 0 ? { ...item, expiresAt: '2098-06-15' } : item);
  assert.deepEqual(accessState(store.get('demo-user-1')), afterRenewal, 'Changing one IA preserves other dates and unlimited access');
  assert.deepEqual(Object.keys(accessBodies[0]).sort(), ['access', 'reason', 'revision']);
  assert.equal(new Set(accessBodies[0].access.map(item => item.agentType)).size, 4);
  assert.deepEqual(accessBodies[0].access, afterRenewal);
  await page.getByRole('button', { name: 'Gerenciar acessos', exact: true }).click();
  await dialog.getByRole('checkbox').last().uncheck();
  await dialog.getByLabel('Motivo da alteração').fill('Revogação parcial simulada');
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  assert.match(await dialog.getByRole('region', { name: /^Revisão de Postagem/ }).innerText(), /Sem acesso \(revogada\)/);
  await dialog.getByRole('button', { name: 'Confirmar na demo' }).click();
  await page.getByText('Alteração salva somente na demonstração.', { exact: true }).waitFor();
  assert.equal(store.get('demo-user-1').access.filter(a => a.effective).length, 3);
  assert.deepEqual(accessState(store.get('demo-user-1')), afterRenewal.map((item, index) => index === 3 ? { ...item, enabled: false } : item), 'Revocation preserves every expiry and other grants');
  console.log('Mixed expiry, single-IA renewal and revocation passed');
  await page.getByRole('button', { name: 'Gerenciar acessos', exact: true }).click();
  await expiries.first().fill('2098-06-20');
  await dialog.getByLabel('Motivo da alteração').fill('Alteração com revisão antiga simulada');
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  const concurrent = store.get('demo-user-1');
  const concurrentAccess = accessState(concurrent).map((item, index) => index === 1 ? { ...item, expiresAt: '2098-07-20' } : item);
  store.setAccess(concurrent.id, { revision: concurrent.revision, access: concurrentAccess, reason: 'Mudança concorrente simulada' }, 'synthetic-admin');
  await dialog.getByRole('button', { name: 'Confirmar na demo' }).click();
  await page.getByRole('alert').filter({ hasText: 'O cadastro mudou. Reabra a edição, confira os dados atualizados e refaça sua alteração.' }).waitFor();
  assert.equal(await dialog.isVisible(), false, 'Stale draft closes after revision conflict');
  assert.deepEqual(accessState(store.get('demo-user-1')), concurrentAccess, 'Stale save cannot overwrite concurrent change');
  await page.getByRole('button', { name: 'Gerenciar acessos', exact: true }).click();
  assert.deepEqual(await expiries.evaluateAll(inputs => inputs.map(input => input.value)), concurrentAccess.map(item => item.expiresAt || ''), 'Reopening starts with refreshed individual dates');
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('button', { name: /Novo usuário/ }).click();
  await dialog.getByLabel('Nome', { exact: true }).fill('Teste Local');
  await dialog.getByLabel('E-mail', { exact: true }).fill('teste@usuarios.example');
  await dialog.getByLabel('Telefone', { exact: true }).fill('+55 11 90000-9900');
  await dialog.getByRole('checkbox').first().check();
  await dialog.getByLabel('Motivo da alteração').fill('Bônus de demonstração');
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  await dialog.getByRole('button', { name: 'Confirmar na demo' }).click();
  await page.getByRole('heading', { name: 'Teste Local', exact: true }).waitFor();
  assert.deepEqual(createBodies[0].agentTypes, ['comunicacao']);
  assert.equal(createBodies[0].expiresAt, null);
  assert.equal('access' in createBodies[0], false, 'Creation retains its common-expiry contract');
  await page.getByRole('button', { name: 'Editar cadastro', exact: true }).click();
  await dialog.getByLabel('Nome', { exact: true }).fill('Teste Local Editado');
  await dialog.getByLabel('Motivo da alteração').fill('Correção fictícia de cadastro');
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  await dialog.getByRole('button', { name: 'Confirmar na demo' }).click();
  await page.getByRole('heading', { name: 'Teste Local Editado', exact: true }).waitFor();
  console.log('Create/profile passed');
  await page.getByRole('button', { name: 'Simular envio de e-mail', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Motivo do convite').fill('Convite de teste local');
  await page.getByRole('dialog').getByRole('button', { name: 'Revisar convite', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Confirmar', exact: true }).click();
  await page.getByText('Envio simulado registrado. Nenhum e-mail foi enviado.', { exact: true }).waitFor();
  const link = await page.getByLabel(/Link de demonstração/).inputValue();
  assert.match(link, /\/auth\/update-password\/demo\?token=/);
  await page.getByLabel('Buscar pessoa').fill('pessoa3@usuarios.example');
  await page.getByRole('button', { name: /Carla Simulada/ }).click();
  await page.getByRole('button', { name: 'Gerenciar acessos', exact: true }).click();
  assert.equal(await dialog.getByRole('checkbox').first().isChecked(), true, 'Renewal preserves expired grants');
  const expiredBefore = accessState(store.get('demo-user-3'));
  await expiries.first().fill('2098-06-01');
  await dialog.getByLabel('Motivo da alteração').fill('Renova somente uma IA vencida');
  await dialog.getByRole('button', { name: 'Revisar alteração' }).click();
  await dialog.getByRole('button', { name: 'Confirmar na demo' }).click();
  await page.getByText('Alteração salva somente na demonstração.', { exact: true }).waitFor();
  assert.deepEqual(accessState(store.get('demo-user-3')), expiredBefore.map((item, index) => index === 0 ? { ...item, expiresAt: '2098-06-01' } : item), 'Renewing an expired IA preserves other expired dates');
  await page.getByLabel('Buscar pessoa').fill('');
  await page.getByRole('combobox', { name: /^IA liberada/ }).selectOption('comunicacao');
  await page.getByRole('combobox', { name: /^Situação/ }).selectOption('active');
  await page.getByRole('button', { name: /Ana Exemplo/ }).waitFor();
  await page.locator('main').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: path.join(screenshotDir, 'admin-users-demo-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(screenshotDir, 'admin-users-demo-mobile.png') });
  apiStatus = 503; await page.reload({ waitUntil: 'networkidle' });
  await page.getByText(/Administração desativada ou indisponível/).waitFor();
  role = 'user'; await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Administração exclusiva para administradores' }).waitFor();
  await context.clearCookies();
  role = 'none';
  await page.goto(link, { waitUntil: 'networkidle' });
  apiStatus = 200;
  await page.getByLabel('Escolha uma senha fictícia').fill('exemplo-ficticio');
  await page.getByLabel('Confirme a senha fictícia').fill('exemplo-ficticio');
  await page.getByRole('button', { name: 'Concluir simulação', exact: true }).click();
  await page.getByRole('heading', { name: 'Simulação concluída' }).waitFor();
  assert.throws(() => store.consumeInvite(new URL(link).searchParams.get('token')));
  assert.deepEqual(errors, []);
  await browser.close();
  console.log(JSON.stringify({ ui: 'passed', create: true, profile: true, accessReview: true, mixedExpiryPreserved: true, singleIaRenewal: true, revocationPreservesDates: true, staleDraftDiscarded: true, expiredRenewal: true, filters: true, invite: true, publicDemoConsume: true, mobileNoOverflow: true, apiDisabled: true, nonAdminDenied: true, allApisIntercepted: true, realEmails: 0, realWrites: 0, screenshotDir }));
})().catch(async err => { console.error(err); await browser?.close(); process.exitCode = 1; });
